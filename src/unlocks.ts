export function unlockName(day: number): string | null {
  if (day < 1) return null
  if (day <= UNLOCKS.length) return UNLOCKS[day - 1]
  const extra = day - UNLOCKS.length - 1
  if (extra < AFTER.length) return AFTER[extra]
  return `Una nueva expansión del aeropuerto, hito ${day}.`
}
